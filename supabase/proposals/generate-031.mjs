// Generates the PROPOSED migration 031 (two-factor for all admin access) and
// its rollback from the CURRENT definitions (a disposable PGlite database
// with 001–030 applied), so each changed function differs from 030 by
// exactly one line. Proposal only: this folder is never applied by any tool.
//
//   node supabase/proposals/generate-031.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PGlite } from '@electric-sql/pglite'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
export const INLINE_LINE = 'select role into v_role from profiles where id = v_actor;'
export const REPLACEMENT = 'v_role := session_role(); -- 031: null for an admin without a two-factor session'
export const INLINE_FUNCTIONS = ['commit_asset_import', 'commit_bulk_import', 'create_asset', 'create_bulk_item', 'onboarding_assign_device', 'perform_bulk_action', 'perform_lifecycle_action', 'perform_swap']

const db = await PGlite.create()
await db.exec(readFileSync(join(ROOT, 'supabase/tests/db/supabase-stub.sql'), 'utf8'))
const mig = join(ROOT, 'supabase/migrations')
for (const f of readdirSync(mig).filter((f) => f.endsWith('.sql')).sort()) {
  let sql = readFileSync(join(mig, f), 'utf8').replace(/create extension if not exists "pgcrypto";/i, '')
  if (f.startsWith('20260901000021')) sql = readFileSync(join(ROOT, 'supabase/adaptations/021_before_drop_changed_functions.sql'), 'utf8') + sql
  await db.exec('begin')
  await db.exec(sql)
  await db.exec('commit')
  if (f.startsWith('20260901000017')) await db.exec(readFileSync(join(ROOT, 'supabase/adaptations/017_after_role_cast.sql'), 'utf8'))
}
const defs = []
for (const name of INLINE_FUNCTIONS) {
  const { rows } = await db.query(`select pg_get_functiondef(p.oid) as d from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = $1`, [name])
  if (rows.length !== 1) throw new Error(`${name}: expected one definition, found ${rows.length}`)
  const d = rows[0].d.replace(/\r\n/g, '\n')
  const hits = d.split(INLINE_LINE).length - 1
  if (hits !== 1) throw new Error(`${name}: expected the inline role read exactly once, found ${hits}`)
  // Other reads of profiles (e.g. an importer's email for a message) are fine; another ROLE read is not.
  if (/\brole\b[^;]*\bfrom\s+profiles/i.test(d.replace(INLINE_LINE, ''))) throw new Error(`${name}: reads profiles.role somewhere else too — review by hand`)
  defs.push({ name, before: d, after: d.replace(INLINE_LINE, REPLACEMENT) })
}
const helpers030 = []
for (const name of ['is_known_user', 'is_editor_or_admin', 'is_admin']) {
  helpers030.push((await db.query(`select pg_get_functiondef('public.${name}()'::regprocedure) as d`)).rows[0].d.replace(/\r\n/g, '\n'))
}
await db.close()

const up = `-- =========================================================================
-- PROPOSAL — NOT A MIGRATION. Not in supabase/migrations/; never applied by
-- any tool. Generated by supabase/proposals/generate-031.mjs from 030.
--
-- Two-factor for ALL administrator access, not only admin powers.
--
-- Today (030) an admin signed in with only a password has no admin powers,
-- but keeps editor-level access: reading everything and editing inventory,
-- checklists, employees and imports. Here, an admin without a two-factor
-- (aal2) session is treated like an account with no access, except that
-- they can read their own profile, so the app can send them to the
-- Security page to verify or enrol. Editors, scanners and viewers are not
-- affected.
--
-- One function, session_role(), decides the caller's effective role for
-- the request (null = no access: unknown, anonymous, revoked, or an admin
-- without two-factor). The three policy helpers and the 8 functions that
-- read profiles.role themselves all go through it, so no path is left
-- that sees the raw role.
--
-- Also: nobody can be MADE an admin through the app unless they already
-- have a verified authenticator (otherwise their password alone could enrol
-- a factor and reach admin powers). A direct database connection (no JWT)
-- can still set roles, for bootstrap and recovery.
--
-- Rollback: supabase/proposals/031_down.sql
-- =========================================================================

create function session_role()
returns user_role
language sql
stable
security definer
set search_path = public
as $$
  select case when p.role = 'admin' and current_aal() <> 'aal2' then null else p.role end
  from profiles p
  where p.id = auth.uid() and p.access_revoked_at is null and not is_anonymous_session();
$$;
revoke execute on function session_role() from public, anon;
grant execute on function session_role() to authenticated;

create or replace function is_known_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select session_role() is not null;
$$;

create or replace function is_editor_or_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(session_role() in ('admin', 'editor'), false);
$$;

create or replace function is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(session_role() = 'admin', false);
$$;

-- An admin without two-factor can still load their own profile (and only
-- that), so the app knows to ask for the code or open the Security page.
create policy profiles_select_self on profiles
  for select using (id = auth.uid() and access_revoked_at is null and not is_anonymous_session());

-- Promotion to admin through the app needs a verified authenticator.
create function require_mfa_for_new_admin()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.role = 'admin' and old.role is distinct from 'admin' and auth.uid() is not null
     and not exists (select 1 from auth.mfa_factors f where f.user_id = new.id and f.status = 'verified') then
    raise exception 'They need to set up two-factor authentication (Security page) before they can be made an admin'
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;
revoke execute on function require_mfa_for_new_admin() from public, anon, authenticated;
create trigger profiles_require_mfa_for_new_admin
  before update on profiles
  for each row execute function require_mfa_for_new_admin();

-- The 8 functions that read profiles.role themselves: one line each
-- (${INLINE_LINE}) becomes session_role().
${defs.map((d) => `${d.after.trim()};`).join('\n\n')}
`

const down = `-- =========================================================================
-- Rollback for the PROPOSED 031 (supabase/proposals/031_admin_mfa_everywhere.sql).
-- Restores the 030 definitions exactly. Generated by generate-031.mjs.
-- =========================================================================
${defs.map((d) => `${d.before.trim()};`).join('\n\n')}

${helpers030.map((d) => `${d.trim()};`).join('\n\n')}

drop trigger profiles_require_mfa_for_new_admin on profiles;
drop function require_mfa_for_new_admin();
drop policy profiles_select_self on profiles;
drop function session_role();
`
writeFileSync(join(ROOT, 'supabase/proposals/031_admin_mfa_everywhere.sql'), up)
writeFileSync(join(ROOT, 'supabase/proposals/031_down.sql'), down)
console.log(`Wrote 031_admin_mfa_everywhere.sql and 031_down.sql (${defs.length} functions, one line each).`)
